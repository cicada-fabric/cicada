package hubaccountwire

import (
	"reflect"
	"strings"
	"time"

	"github.com/cicada-ai/cicada/internal/e2ee"
)

// These helpers must run after authenticating the pinned Hub response and before
// displaying/signing its target. Original DTO/packet pairs come from the same
// durable local outbox. They do not authorize current server-side admission.
func ValidateNativePairBootstrapChallenge(ch NativePairBootstrapChallenge, hub HubIdentity, now time.Time) error {
	if ch.Format != NativePairFormat || ValidateNativePairScope(ch.Scope, hub) != nil || !isHex(ch.RequestID, RequestIDBytes) || !isHex(ch.RequestPacketDigest, 32) ||
		ch.Bootstrap.PrepareRequestID != ch.RequestID || ch.Bootstrap.PreparePacketDigest != ch.RequestPacketDigest || ch.ObservedAt != ch.Bootstrap.PreparedAt {
		return ErrInvalid
	}
	prepared, err := parseCanonicalUTC(ch.Bootstrap.PreparedAt)
	if err != nil {
		return ErrInvalid
	}
	end := prepared.Add(5 * time.Minute)
	session, _ := parseCanonicalUTC(ch.Scope.Actor.AccountSessionExpiresAt)
	if session.Before(end) {
		end = session
	}
	if ch.ProofExpiresAt != formatUTC(end) {
		return ErrInvalid
	}
	// Validate the exact commit target without signing it or reusing the prepare
	// request ID. Fresh complete request ID/nonce must be generated by the App.
	id := strings.Repeat("0", 32)
	if id == ch.RequestID {
		id = strings.Repeat("1", 32)
	}
	c := e2ee.OwnerNativePairClaims{Version: 1, Purpose: e2ee.OwnerNativePairBootstrapCommit, Scope: ch.Scope, RequestID: id, Nonce: strings.Repeat("0", 64), IssuedAt: ch.Bootstrap.PreparedAt, ExpiresAt: ch.ProofExpiresAt, Bootstrap: &ch.Bootstrap}
	if e2ee.ValidateOwnerNativePairClaims(c, now) != nil {
		return ErrInvalid
	}
	return nil
}

func ValidateNativePairBootstrapTarget(q NativePairBootstrapPrepare, original []byte, ch NativePairBootstrapChallenge, hub HubIdentity, now time.Time) error {
	if now.IsZero() || validateNativePairRequest(q, hub, time.Time{}) != nil || ValidateNativePairBootstrapChallenge(ch, hub, now) != nil {
		return ErrInvalid
	}
	p, err := nativePairOriginal(original)
	if err != nil || p.Packet.Route.Operation != OperationNativePairBootstrapPrepare || p.Packet.Route.OperationID != q.Context.RequestID || ch.RequestID != q.Context.RequestID ||
		ch.RequestPacketDigest != NativePairPacketDigest(original) || validateNativePairDevice(q, p.SenderPublicIdentity) != nil {
		return ErrInvalid
	}
	c, err := e2ee.VerifyOwnerNativePair(ch.Scope.Actor.OwnerPublic, q.OwnerProof, e2ee.OwnerNativePairBootstrapPreview, time.Time{})
	if err != nil || (!reflect.DeepEqual(c.Scope.Actor, ch.Scope.Actor) || !reflect.DeepEqual(c.Scope.Node, ch.Scope.Node)) || c.Bootstrap.GroupLabel != ch.Bootstrap.GroupLabel || c.Bootstrap.Runtime != ch.Bootstrap.Runtime || c.Bootstrap.SlotCount != ch.Bootstrap.SlotCount || c.Bootstrap.Policy != ch.Bootstrap.Policy {
		return ErrInvalid
	}
	return nil
}

// The retained bootstrap proof supplies the chosen Network/Group/deadline;
// the signed local preview supplies both reviewed slot digests and Node tuple.
func ValidateNativePairPlanTarget(q NativePairConsentPrepare, original []byte, ch NativePairPlanChallenge, bootstrapProof []byte, hub HubIdentity, now time.Time) error {
	if now.IsZero() || validateNativePairRequest(q, hub, time.Time{}) != nil || ch.Format != NativePairFormat || ValidateNativePairPlanForConsent(ch.Plan, hub, now) != nil || ch.ObservedAt != ch.Plan.PreparedAt {
		return ErrInvalid
	}
	p, err := nativePairOriginal(original)
	if err != nil || p.Packet.Route.Operation != OperationNativePairConsentPrepare || p.Packet.Route.OperationID != q.Context.RequestID || ch.RequestID != q.Context.RequestID || ch.RequestPacketDigest != NativePairPacketDigest(original) || validateNativePairDevice(q, p.SenderPublicIdentity) != nil {
		return ErrInvalid
	}
	c, err := e2ee.VerifyOwnerNativePair(ch.Plan.Scope.Actor.OwnerPublic, q.OwnerProof, e2ee.OwnerNativePairConsentPreview, time.Time{})
	if err != nil {
		return ErrInvalid
	}
	a, _ := NativePairSlotDigest(ch.Plan.SlotA)
	b, _ := NativePairSlotDigest(ch.Plan.SlotB)
	if !reflect.DeepEqual(c.Scope, ch.Plan.Scope) || c.Consent.PairID != ch.Plan.PairID || c.Consent.ExpectedRevision != ch.Plan.ExpectedRevision || c.Consent.SlotADigest != a || c.Consent.SlotBDigest != b || c.Consent.PeerExpiresAt != ch.Plan.PeerExpiresAt {
		return ErrInvalid
	}
	bp, err := e2ee.VerifyOwnerNativePair(c.Scope.Actor.OwnerPublic, bootstrapProof, e2ee.OwnerNativePairBootstrapCommit, time.Time{})
	if err != nil || bp.Bootstrap.PairID != ch.Plan.PairID || bp.Bootstrap.NetworkID != ch.Plan.NetworkID || bp.Bootstrap.GroupID != ch.Plan.GroupID || bp.Bootstrap.PeerExpiresAt != ch.Plan.PeerExpiresAt || bp.Bootstrap.Policy != ch.Plan.Policy || NativePairProofDigest(bootstrapProof) != ch.Plan.BootstrapProofDigest || !nativePairSameStableScope(bp.Scope, c.Scope) {
		return ErrInvalid
	}
	return nil
}
