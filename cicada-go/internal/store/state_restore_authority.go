const hubRestoreAuthorityDirectory = ".hub-restore-authority"
const hubRestoreSourceMarker = ".hub-restore-source.json"

var ErrHubRestoreAuthorityUnproven = errors.New("AUTHORITY_UNPROVEN: independent continuous SOURCE authority is unavailable")
var ErrHubRestoreCoverage = errors.New("Hub restore coverage incomplete or rollback detected")
var ErrHubRestoreExecutionPending = errors.New("Hub restore execution is not quiescent")

type HubRestoreStorageIncarnation struct {
	CanonicalCoordinate string `json:"canonical_coordinate"`
	Device              uint64 `json:"device"`
	Inode               uint64 `json:"inode"`
	RegistrationNonce   string `json:"registration_nonce"`
}

// HubRestoreTrustPin is supplied by the independent established deployment,
// never generated by RegisterEstablishedHubSource or from a restored archive.
type HubRestoreTrustPin struct {
	FormatVersion        int                          `json:"format_version"`
	HubID                string                       `json:"hub_id"`
	SourceStorage        HubRestoreStorageIncarnation `json:"source_storage_incarnation"`
	IdentityFingerprints map[string]string            `json:"identity_fingerprints"`
	SchemaFingerprint    string                       `json:"schema_fingerprint"`
	TrustReferenceSHA256 string                       `json:"trust_reference_sha256"`
}
type HubRestoreRegistrationOptions struct{ SourceStateDir, IndependentTrustFile, IndependentTrustSHA256 string }
type HubRestorePrepareOptions struct{ SourceStateDir, BaseBackupDir, CapsuleDir, TargetStateDir string }
type HubRestoreOperationOptions struct{ SourceStateDir, TargetStateDir string }
type HubRestoreAuthority struct {
	FormatVersion           int                            `json:"format_version"`
	AuthorityID             string                         `json:"authority_id"`
	AuthorityEpoch          uint64                         `json:"authority_epoch"`
	State                   string                         `json:"state"`
	TrustPinSHA256          string                         `json:"independent_trust_reference_digest"`
	TrustPin                HubRestoreTrustPin             `json:"trust_pin"`
	SourceStorage           HubRestoreStorageIncarnation   `json:"source_storage_incarnation"`
	TargetStateDir          string                         `json:"canonical_target_coordinate,omitempty"`
	TargetStorage           *HubRestoreStorageIncarnation  `json:"target_storage_incarnation,omitempty"`
	BaseBackupDir           string                         `json:"base_backup_dir,omitempty"`
	CapsuleDir              string                         `json:"capsule_dir,omitempty"`
	BaseManifestSHA256      string                         `json:"base_backup_B_manifest_sha256,omitempty"`
	CapsuleManifestSHA256   string                         `json:"current_capsule_C_manifest_sha256,omitempty"`
	InventorySHA256         string                         `json:"full_payload_inventory_digest,omitempty"`
	CoverageSHA256          string                         `json:"coverage_digest,omitempty"`
	UnknownSHA256           string                         `json:"unknown_tombstone_digest,omitempty"`
	HoldSHA256              string                         `json:"original_hold_sha256,omitempty"`
	PriorRecordSHA256       string                         `json:"prior_authority_record_digest,omitempty"`
	ActivationReceiptSHA256 string                         `json:"activation_receipt_digest,omitempty"`
	TransitionNonce         string                         `json:"transition_nonce"`
	RetiredSources          []HubRestoreStorageIncarnation `json:"retired_sources,omitempty"`
}
type hubRestoreLocator struct {
	Version       int    `json:"version"`
	AuthorityPath string `json:"authority_path"`
	AuthorityID   string `json:"authority_id"`
	Nonce         string `json:"registration_nonce"`
}

func hubRestoreHash(b []byte) string { h := sha256.Sum256(b); return hex.EncodeToString(h[:]) }
func hubRestoreDigest(v any) string  { b, _ := json.Marshal(v); return hubRestoreHash(b) }
func hubRestoreNonce() (string, error) {
	b := make([]byte, 32)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return hex.EncodeToString(b), nil
}
func hubRestoreDigestValid(s string) bool {
	b, e := hex.DecodeString(s)
	return e == nil && len(b) == 32 && hex.EncodeToString(b) == s
}
func hubRestorePrivateFile(info os.FileInfo) bool {
	if info.Mode() != 0600 {
		return false
	}
	v := reflect.ValueOf(info.Sys())
	if v.Kind() != reflect.Pointer || v.IsNil() {
		return false
	}
	u := v.Elem().FieldByName("Uid")
	return u.IsValid() && u.CanUint() && u.Uint() == uint64(os.Geteuid())
}
func hubRestoreReadPrivateFile(path string) ([]byte, error) {
	// Every parent must be a real directory; aliases are not trust coordinates.
	abs, e := filepath.Abs(path)
	if e != nil || abs != filepath.Clean(path) {
		return nil, ErrStateBackupPathUnsafe
	}
	for p := filepath.Dir(abs); ; p = filepath.Dir(p) {
		i, e := os.Lstat(p)
		if e != nil || !i.IsDir() || i.Mode()&os.ModeSymlink != 0 {
			return nil, ErrStateBackupPathUnsafe
		}
		if p == string(filepath.Separator) {
			break
		}
	}
	i, e := os.Lstat(abs)
	if e != nil {
		return nil, e
	}
	if !hubRestorePrivateFile(i) || i.Size() > 4<<20 {
		return nil, ErrStateBackupPathUnsafe
	}
	f, e := os.Open(abs)
	if e != nil {
		return nil, e
	}
	defer f.Close()
	held, e := f.Stat()
	if e != nil || !os.SameFile(i, held) {
		return nil, ErrStateBackupPathUnsafe
	}
	b, e := io.ReadAll(io.LimitReader(f, (4<<20)+1))
	if e != nil || len(b) > 4<<20 {
		return nil, ErrStateBackupPathUnsafe
	}
	after, e := os.Lstat(abs)
	if e != nil || !sameStableFile(i, after) || !hubRestorePrivateFile(after) {
		return nil, ErrStateBackupPathUnsafe
	}
	return b, nil
}
func hubRestoreReadJSON(path string, value any) ([]byte, error) {
	b, e := hubRestoreReadPrivateFile(path)
	if e != nil {
		return nil, e
	}
	d := json.NewDecoder(bytes.NewReader(b))
	d.DisallowUnknownFields()
	if e = d.Decode(value); e != nil {
		return nil, e
	}
	if e = d.Decode(new(any)); e != io.EOF {
		return nil, ErrStateBackupPathUnsafe
	}
	return b, nil
}
func hubRestoreIncarnation(path, nonce string) (HubRestoreStorageIncarnation, error) {
	c, e := canonicalRestoreTarget(path)
	if e != nil || c != path {
		return HubRestoreStorageIncarnation{}, ErrStateBackupPathUnsafe
	}
	i, e := os.Lstat(c)
	if e != nil || !stateRestorePrivateDirectory(i) {
		return HubRestoreStorageIncarnation{}, ErrStateBackupPathUnsafe
	}
	v := reflect.ValueOf(i.Sys())
	dev := v.Elem().FieldByName("Dev")
	ino := v.Elem().FieldByName("Ino")
	if !dev.IsValid() || !ino.IsValid() || !dev.CanUint() || !ino.CanUint() || ino.Uint() == 0 {
		return HubRestoreStorageIncarnation{}, ErrStateBackupPathUnsafe
	}
	return HubRestoreStorageIncarnation{c, dev.Uint(), ino.Uint(), nonce}, nil
}
func hubRestoreIncarnationMatches(expected HubRestoreStorageIncarnation, path string) bool {
	actual, e := hubRestoreIncarnation(path, expected.RegistrationNonce)
	return e == nil && actual == expected
}
func hubRestoreAuthorityPath(source string) string {
	return filepath.Join(filepath.Dir(source), hubRestoreAuthorityDirectory, hubRestoreHash([]byte(source))+".json")
}
func hubRestoreSourceLocatorPath(source string) string {
	return filepath.Join(filepath.Dir(source), hubRestoreAuthorityDirectory, hubRestoreHash([]byte(source))+".source.json")
}
func hubRestoreTargetLocatorPath(target string) string {
	return filepath.Join(filepath.Dir(target), hubRestoreAuthorityDirectory, hubRestoreHash([]byte(target))+".target.json")
}
func hubRestoreCheckAuthorityDirectory(path string) error {
	i, e := os.Lstat(filepath.Dir(path))
	if e != nil || !stateRestorePrivateDirectory(i) {
		return ErrHubRestoreAuthorityUnproven
	}
	return nil
}
func hubRestoreWriteAtomic(path string, v any) error {
	if e := hubRestoreCheckAuthorityDirectory(path); e != nil {
		return e
	}
	b, e := json.MarshalIndent(v, "", "  ")
	if e != nil {
		return e
	}
	b = append(b, '\n')
	f, e := os.CreateTemp(filepath.Dir(path), ".authority-partial-")
	if e != nil {
		return e
	}
	tmp := f.Name()
	defer os.Remove(tmp)
	if e = f.Chmod(0600); e == nil {
		_, e = f.Write(b)
	}
	if e == nil {
		e = f.Sync()
	}
	ce := f.Close()
	if e == nil {
		e = ce
	}
	if e != nil {
		return e
	}
	if e = os.Rename(tmp, path); e != nil {
		return e
	}
	return syncDirectory(filepath.Dir(path))
}
func ReadExistingHubRestoreAuthority(sourceStateDir string) (*HubRestoreAuthority, error) {
	source, e := canonicalRestoreTarget(sourceStateDir)
	if e != nil {
		return nil, e
	}
	path, e := hubRestoreLocate(source)
	if e != nil {
		return nil, e
	}
	return hubRestoreReadAuthority(path)
}
func hubRestoreLocate(state string) (string, error) {
	var loc hubRestoreLocator
	if _, e := os.Lstat(filepath.Join(state, hubRestoreSourceMarker)); e == nil {
		if _, e = hubRestoreReadJSON(filepath.Join(state, hubRestoreSourceMarker), &loc); e != nil {
			return "", ErrHubRestoreAuthorityUnproven
		}
	} else if !errors.Is(e, os.ErrNotExist) {
		return "", e
	} else {
		path := hubRestoreSourceLocatorPath(state)
		if _, e = os.Lstat(path); errors.Is(e, os.ErrNotExist) {
			path = hubRestoreTargetLocatorPath(state)
		}
		if e = hubRestoreCheckAuthorityDirectory(path); e != nil {
			return "", e
		}
		if _, e = hubRestoreReadJSON(path, &loc); e != nil {
			return "", ErrHubRestoreAuthorityUnproven
		}
	}
	if loc.Version != 1 || loc.AuthorityID == "" || !hubRestoreDigestValid(loc.Nonce) || filepath.Dir(loc.AuthorityPath) != filepath.Join(filepath.Dir(state), hubRestoreAuthorityDirectory) {
		return "", ErrHubRestoreAuthorityUnproven
	}
	if e := hubRestoreCheckAuthorityDirectory(loc.AuthorityPath); e != nil {
		return "", e
	}
	a, e := hubRestoreReadAuthority(loc.AuthorityPath)
	if e != nil || a.AuthorityID != loc.AuthorityID {
		return "", ErrHubRestoreAuthorityUnproven
	}
	return loc.AuthorityPath, nil
}
func hubRestoreReadAuthority(path string) (*HubRestoreAuthority, error) {
	if e := hubRestoreCheckAuthorityDirectory(path); e != nil {
		return nil, e
	}
	var a HubRestoreAuthority
	if _, e := hubRestoreReadJSON(path, &a); e != nil {
		return nil, ErrHubRestoreAuthorityUnproven
	}
	if a.FormatVersion != 1 || a.AuthorityEpoch == 0 || !hubRestoreDigestValid(a.AuthorityID) || !hubRestoreDigestValid(a.TrustPinSHA256) || !hubRestoreDigestValid(a.TransitionNonce) || a.TrustPin.FormatVersion != 1 || a.TrustPin.HubID == "" {
		return nil, ErrHubRestoreAuthorityUnproven
	}
	switch a.State {
	case "ACTIVE_SOURCE":
		if a.TargetStorage != nil {
			return nil, ErrHubRestoreAuthorityUnproven
		}
	case "SEALED", "FENCED":
		if a.TargetStateDir == "" || a.TargetStorage != nil {
			return nil, ErrHubRestoreAuthorityUnproven
		}
	case "ACTIVE_TARGET":
		if a.TargetStorage == nil || !hubRestoreDigestValid(a.ActivationReceiptSHA256) {
			return nil, ErrHubRestoreAuthorityUnproven
		}
	default:
		return nil, ErrHubRestoreAuthorityUnproven
	}
	return &a, nil
}

// Registration consumes an already established external pin; SOURCE cannot
// manufacture freshness by writing its own pin or by absence of quarantine.
func RegisterEstablishedHubSource(ctx context.Context, o HubRestoreRegistrationOptions) (*HubRestoreAuthority, error) {
	if ctx == nil {
		ctx = context.Background()
	}
	source, e := canonicalRestoreTarget(o.SourceStateDir)
	if e != nil {
		return nil, e
	}
	trust, e := filepath.Abs(o.IndependentTrustFile)
	if e != nil || !hubRestoreDigestValid(o.IndependentTrustSHA256) || statePathsOverlap(source, trust) {
		return nil, ErrHubRestoreAuthorityUnproven
	}
	if i, e := os.Lstat(filepath.Dir(trust)); e != nil || !stateRestorePrivateDirectory(i) {
		return nil, fmt.Errorf("%w: independent deployment pin parent is not private", ErrHubRestoreAuthorityUnproven)
	}
	var pin HubRestoreTrustPin
	b, e := hubRestoreReadJSON(trust, &pin)
	if e != nil {
		return nil, fmt.Errorf("%w: independent deployment pin cannot be read", ErrHubRestoreAuthorityUnproven)
	}
	if hubRestoreHash(b) != o.IndependentTrustSHA256 {
		return nil, fmt.Errorf("%w: independent deployment pin digest mismatch", ErrHubRestoreAuthorityUnproven)
	}
	if pin.FormatVersion != 1 || pin.HubID == "" || !hubRestoreDigestValid(pin.TrustReferenceSHA256) || !hubRestoreDigestValid(pin.SourceStorage.RegistrationNonce) {
		return nil, fmt.Errorf("%w: independent deployment pin shape", ErrHubRestoreAuthorityUnproven)
	}
	if !hubRestoreIncarnationMatches(pin.SourceStorage, source) {
		return nil, fmt.Errorf("%w: independent deployment pin SOURCE incarnation mismatch", ErrHubRestoreAuthorityUnproven)
	}
	// An old restored or registered incarnation cannot be bootstrapped anew.
	for _, p := range []string{filepath.Join(source, hubRestoreSourceMarker), filepath.Join(source, stateRestoreMarker), stateRestoreRegistrationPath(source), hubRestoreTargetLocatorPath(source), hubRestoreSourceLocatorPath(source), hubRestoreAuthorityPath(source)} {
		if _, e = os.Lstat(p); !errors.Is(e, os.ErrNotExist) {
			return nil, fmt.Errorf("%w: SOURCE already has restore or registration lineage", ErrHubRestoreAuthorityUnproven)
		}
	}
	lease, e := acquireStateMaintenance(source, true, false)
	if e != nil {
		return nil, e
	}
	defer lease.Close()
	if e = lease.validate(source); e != nil {
		return nil, e
	}
	if !hubRestoreIncarnationMatches(pin.SourceStorage, source) {
		return nil, ErrHubRestoreAuthorityUnproven
	}
	cp, e := InspectHubRestoreCheckpointReadOnly(source)
	if e != nil {
		return nil, e
	}
	if cp.HubID != pin.HubID || cp.SchemaFingerprint != pin.SchemaFingerprint || hubRestoreDigest(cp.IdentityFingerprints) != hubRestoreDigest(pin.IdentityFingerprints) {
		return nil, fmt.Errorf("%w: independent deployment pin identity or schema mismatch", ErrHubRestoreAuthorityUnproven)
	}
	path := hubRestoreAuthorityPath(source)
	dir := filepath.Dir(path)
	if e = os.Mkdir(dir, 0700); e != nil && !errors.Is(e, os.ErrExist) {
		return nil, e
	}
	if e = hubRestoreCheckAuthorityDirectory(path); e != nil {
		return nil, e
	}
	al, e := acquireStateMaintenance(dir, true, false)
	if e != nil {
		return nil, e
	}
	defer al.Close()
	if _, e = os.Lstat(path); !errors.Is(e, os.ErrNotExist) {
		return nil, ErrHubRestoreAuthorityUnproven
	}
	id, e := hubRestoreNonce()
	if e != nil {
		return nil, e
	}
	nonce, e := hubRestoreNonce()
	if e != nil {
		return nil, e
	}
	a := &HubRestoreAuthority{FormatVersion: 1, AuthorityID: id, AuthorityEpoch: 1, State: "ACTIVE_SOURCE", TrustPinSHA256: o.IndependentTrustSHA256, TrustPin: pin, SourceStorage: pin.SourceStorage, TransitionNonce: nonce}
	// Sentinel first: a missing/half-written anchor is a hold, never ordinary startup.
	loc := hubRestoreLocator{1, path, id, pin.SourceStorage.RegistrationNonce}
	if e = writePrivateJSON(hubRestoreSourceLocatorPath(source), loc); e != nil {
		return nil, e
	}
	if e = syncDirectory(dir); e != nil {
		return nil, e
	}
	if e = writePrivateJSON(filepath.Join(source, hubRestoreSourceMarker), loc); e != nil {
		return nil, e
	}
	if e = syncDirectory(source); e != nil {
		return nil, e
	}
	if e = hubRestoreWriteAtomic(path, a); e != nil {
		return nil, e
	}
	if e = syncDirectory(filepath.Dir(dir)); e != nil {
		return nil, e
	}
	return a, nil
}
func PrepareHubRestoreHandover(ctx context.Context, o HubRestorePrepareOptions) (*HubRestoreAuthority, error) {
	if ctx == nil {
		ctx = context.Background()
	}
	// Check supplied coordinates before canonicalRestoreTarget could erase a
	// parent alias. In particular the capsule must never physically enter SOURCE.
	if e := validateStatePathSeparation(o.SourceStateDir, o.TargetStateDir, o.BaseBackupDir, o.CapsuleDir); e != nil {
		return nil, e
	}
	source, e := canonicalRestoreTarget(o.SourceStateDir)
	if e != nil {
		return nil, e
	}
	target, e := canonicalRestoreTarget(o.TargetStateDir)
	if e != nil || filepath.Dir(target) != filepath.Dir(source) {
		return nil, ErrStateBackupPathUnsafe
	}
	base, e := filepath.Abs(o.BaseBackupDir)
	if e != nil {
		return nil, e
	}
	capsule, e := filepath.Abs(o.CapsuleDir)
	if e != nil {
		return nil, e
	}
	paths := []string{source, target, base, capsule, filepath.Dir(hubRestoreAuthorityPath(source))}
	if e := validateStatePathSeparation(paths...); e != nil {
		return nil, e
	}
	path, e := hubRestoreLocate(source)
	if e != nil {
		return nil, e
	}
	al, e := acquireStateMaintenance(filepath.Dir(path), true, false)
	if e != nil {
		return nil, e
	}
	defer al.Close()
	lease, e := acquireStateMaintenance(source, true, false)
	if e != nil {
		return nil, e
	}
	defer lease.Close()
	a, e := hubRestoreReadAuthority(path)
	if e != nil {
		return nil, e
	}
	if e = hubRestoreVerifyStartupAuthority(source, a, path); e != nil {
		return nil, e
	}
	previousRecord, e := hubRestoreReadPrivateFile(path)
	if e != nil {
		return nil, e
	}
	prior := hubRestoreHash(previousRecord)
	if a.State == "ACTIVE_TARGET" {
		a.RetiredSources = append(a.RetiredSources, a.SourceStorage)
		a.SourceStorage = *a.TargetStorage
		a.TargetStorage = nil
		a.AuthorityEpoch++
	}
	allowed, e := hubRestoreBackupAllowlist(source)
	if e != nil {
		return nil, e
	}
	cp, e := InspectHubRestoreCheckpointReadOnly(source)
	if e != nil {
		return nil, e
	}
	if cp.HubID != a.TrustPin.HubID || hubRestoreDigest(cp.IdentityFingerprints) != hubRestoreDigest(a.TrustPin.IdentityFingerprints) || cp.SchemaFingerprint != a.TrustPin.SchemaFingerprint {
		return nil, ErrHubRestoreAuthorityUnproven
	}
	if e = RequireHubRestoreExecutionQuiescent(cp); e != nil {
		return nil, e
	}
	bm, e := VerifyStateBackup(base)
	if e != nil {
		return nil, e
	}
	if e = ensureBackupDestinationIsNew(capsule); e != nil {
		return nil, e
	}
	// Persist the SOURCE fence before capturing anything; a crash stays held.
	a.State = "FENCED"
	a.PriorRecordSHA256 = prior
	a.TargetStateDir = target
	a.BaseBackupDir = base
	a.CapsuleDir = capsule
	a.BaseManifestSHA256 = hubRestoreDigest(bm)
	a.ActivationReceiptSHA256 = ""
	a.TransitionNonce, e = hubRestoreNonce()
	if e != nil {
		return nil, e
	}
	if e = hubRestoreWriteAtomic(path, a); e != nil {
		return nil, e
	}
	cm, e := backupStateDirUnderMaintenance(ctx, StateBackupOptions{source, capsule}, lease, allowed)
	if e != nil {
		return nil, e
	}
	current, e := InspectHubRestoreCheckpointReadOnly(filepath.Join(capsule, stateBackupPayloadName))
	if e != nil {
		return nil, e
	}
	old, e := InspectHubRestoreCheckpointReadOnly(filepath.Join(base, stateBackupPayloadName))
	if e != nil {
		return nil, e
	}
	if e = CompareHubRestoreCoverage(old, current); e != nil {
		return nil, e
	}
	if e = RequireHubRestoreExecutionQuiescent(current); e != nil {
		return nil, e
	}
	a.CapsuleManifestSHA256 = hubRestoreDigest(cm)
	a.InventorySHA256 = hubRestoreDigest(cm.Files)
	a.CoverageSHA256 = current.CoverageSHA256
	a.UnknownSHA256 = current.UnknownSHA256
	a.State = "SEALED"
	// The target locator is created under its held restore lease during forward.
	// Publishing it here would incorrectly block the original B restore itself.
	if e = lease.validate(source); e != nil {
		return nil, e
	}
	if e = hubRestoreWriteAtomic(path, a); e != nil {
		return nil, e
	}
	return a, nil
}
func hubRestoreIdentityFingerprints(root string) (map[string]string, error) {
	out := map[string]string{}
	for _, name := range []string{"identity.json", "client-control-identity.json", "node-control-identity.json"} {
		b, e := hubRestoreReadPrivateFile(filepath.Join(root, "e2ee", name))
		if e != nil {
			return nil, e
		}
		id, e := e2ee.UnmarshalIdentity(b)
		if e != nil {
			return nil, e
		}
		fp, e := e2ee.OwnerDevicePublicKeyFingerprint(id.Public())
		if e != nil {
			return nil, e
		}
		out[name] = fp
	}
	return out, nil
}
func hubRestoreBackupAllowlist(source string) (map[string]string, error) {
	allowed := map[string]string{}
	_, se := os.Lstat(filepath.Join(source, hubRestoreSourceMarker))
	_, he := os.Lstat(filepath.Join(source, stateRestoreMarker))
	if errors.Is(se, os.ErrNotExist) && errors.Is(he, os.ErrNotExist) {
		return allowed, nil
	}
	path, e := hubRestoreLocate(source)
	if e != nil {
		return nil, e
	}
	a, e := hubRestoreReadAuthority(path)
	if e != nil {
		return nil, e
	}
	if e = hubRestoreVerifyStartupAuthority(source, a, path); e != nil {
		return nil, e
	}
	if se == nil {
		b, e := hubRestoreReadPrivateFile(filepath.Join(source, hubRestoreSourceMarker))
		if e != nil {
			return nil, e
		}
		allowed[hubRestoreSourceMarker] = hubRestoreHash(b)
	}
	if he == nil {
		b, e := hubRestoreReadPrivateFile(filepath.Join(source, stateRestoreMarker))
		if e != nil {
			return nil, e
		}
		allowed[stateRestoreMarker] = hubRestoreHash(b)
	}
	return allowed, nil
}
func hubRestoreVerifyStartupAuthority(state string, a *HubRestoreAuthority, path string) error {
	if a.State == "ACTIVE_SOURCE" && hubRestoreIncarnationMatches(a.SourceStorage, state) {
		fps, e := hubRestoreIdentityFingerprints(state)
		if e != nil || hubRestoreDigest(fps) != hubRestoreDigest(a.TrustPin.IdentityFingerprints) {
			return ErrHubRestoreAuthorityUnproven
		}
		return nil
	}
	if a.State != "ACTIVE_TARGET" || a.TargetStorage == nil || a.TargetStateDir != state || !hubRestoreIncarnationMatches(*a.TargetStorage, state) {
		return ErrHubRestoreAuthorityUnproven
	}
	return VerifyHubActivationReceipt(state, path, a)
}

// Kept separate from activation so ordinary writes after the first permit do
// not have to match the sealed capsule's original SQLite checksum.
func hubRestoreStartupPermission(state string) (bool, error) {
	for _, p := range []string{filepath.Join(state, hubRestoreSourceMarker), hubRestoreSourceLocatorPath(state), hubRestoreTargetLocatorPath(state), hubRestoreAuthorityPath(state)} {
		if _, e := os.Lstat(p); e == nil {
			path, e := hubRestoreLocate(state)
			if e != nil {
				return true, e
			}
			a, e := hubRestoreReadAuthority(path)
			if e != nil {
				return true, e
			}
			return true, hubRestoreVerifyStartupAuthority(state, a, path)
		} else if !errors.Is(e, os.ErrNotExist) {
			return true, e
		}
	}
	return false, nil
}

// Unix times are metadata only, not a freshness authority.
func hubRestoreNow() string { return time.Now().UTC().Format(time.RFC3339Nano) }
